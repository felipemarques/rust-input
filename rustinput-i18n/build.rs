//! Compiles the translations (`po/<language>.po`) into the program: one
//! table per language, sorted by English text, in `$OUT_DIR/catalogs.rs`.

use std::{env, fmt::Write as _, fs, path::Path};

#[path = "src/po.rs"]
#[allow(dead_code)]
mod po;

fn main() {
    println!("cargo:rerun-if-changed=po");
    let po_dir = Path::new("po");
    let mut files: Vec<_> = fs::read_dir(po_dir)
        .expect("the folder po")
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "po"))
        .collect();
    files.sort();

    let mut out = String::from("// generated by build.rs from po/*.po\n");
    out.push_str("static CATALOGS: &[(&str, &[(&str, &str)])] = &[\n");
    for path in files {
        println!("cargo:rerun-if-changed={}", path.display());
        let name = path.file_stem().unwrap().to_string_lossy().into_owned();
        let source = fs::read_to_string(&path).expect("a PO file");
        let entries = po::parse(&source).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let mut pairs: Vec<(String, String)> = entries
            .into_iter()
            .filter(|e| !e.fuzzy && !e.text.is_empty())
            .map(|e| (e.key(), e.text))
            .collect();
        pairs.sort();
        pairs.dedup_by(|a, b| a.0 == b.0);
        writeln!(out, "    ({name:?}, &[").unwrap();
        for (key, text) in pairs {
            writeln!(out, "        ({key:?}, {text:?}),").unwrap();
        }
        out.push_str("    ]),\n");
    }
    out.push_str("];\n");
    let dest = Path::new(&env::var("OUT_DIR").unwrap()).join("catalogs.rs");
    fs::write(dest, out).expect("catalogs.rs written");
}
